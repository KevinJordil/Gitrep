test('review prompts: a prompt of this repository overrides the global ones, and Claude gets it', async () => {
  await v.getByRole('button', { name: 'Review', exact: true }).click()
  await dialog().getByRole('button', { name: 'Edit prompts…' }).click()
  const prompts = page.getByRole('dialog', { name: 'Review prompts' })
  await prompts.getByLabel('This repository (alpha) uses its own prompt').check()
  await prompts.getByLabel("Name of this repository's prompt").fill('Firmware safety review')
  await prompts.getByLabel("Text of this repository's prompt").fill('Focus on ISR re-entrancy.')
  await prompts.getByRole('button', { name: 'Add prompt' }).click()
  await prompts.getByLabel('Name of prompt 2').fill('Default review')
  await expect(prompts).toContainText('Two prompts have the same name.')
  await expect(prompts.getByRole('button', { name: 'Save' })).toBeDisabled()
  await prompts.getByLabel('Name of prompt 2').fill('Java style')
  await prompts.getByLabel('Text of prompt 2').fill('Check Java conventions.')
  await page.screenshot({ path: 'e2e-artifacts/review-prompts.png' })
  await prompts.getByRole('button', { name: 'Save' }).click()
  await expect(prompts).toHaveCount(0)
  await expect(dialog().getByLabel('Review prompt')).toHaveValue('repo')
  await expect(dialog().locator('.badge', { hasText: 'Repo override' })).toBeVisible()
  await expect(dialog().locator('.prompt-pre')).toHaveText('Focus on ISR re-entrancy.')
  await expect(dialog()).toContainText('Other prompts: Default review (global) · Java style (global)')
  const config = JSON.parse(readFileSync(join(fx.root, 'userData', 'config.json'), 'utf8'))
  expect(config.repos.find((r: { name: string }) => r.name === 'alpha').reviewPrompt).toEqual({ name: 'Firmware safety review', text: 'Focus on ISR re-entrancy.' })
  expect(config.settings.reviewPrompts.map((p: { name: string }) => p.name)).toEqual(['Default review', 'Java style'])
  await dialog().getByLabel('Compare with').selectOption('main')
  await dialog().getByRole('button', { name: 'Start review' }).click()
  await expect(v.getByRole('region', { name: 'Review' })).toContainText('Firmware safety review')
  expect(readFileSync(join(fx.root, 'review-args'), 'utf8')).toContain('Review instructions from the user:\nFocus on ISR re-entrancy.')
  await v.getByRole('button', { name: 'Exit review' }).click()
})
