test('blame: the commit of each chunk, hover and select, blame at parent through the rename', async () => {
  await v.locator('aside.right .file', { hasText: 'guide.md' }).getByRole('button').first().click()
  await v.getByRole('button', { name: 'Blame', exact: true }).click()
  await expect(v.getByRole('group', { name: 'File view' }).getByRole('button', { name: 'Blame' })).toHaveAttribute('aria-pressed', 'true')
  await expect(head()).toContainText('Revision: HEAD')
  await expect(entry('docs: move guide')).toHaveAttribute('aria-selected', 'true') // HEAD is not in the list: the newest entry
  await expect(v.locator('.bl-line')).toHaveCount(10)
  await expect(chunks()).toHaveText(['docs: add guide', 'docs: edit guide', 'docs: add guide', 'docs: move guide', 'docs: add guide'])
  await v.locator('.bl-line', { hasText: 'nine' }).hover()
  await expect(entry('docs: move guide')).toHaveClass(/hl/)
  await expect(v.locator('.bl-line', { hasText: 'nine' })).not.toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await expect(v.locator('.bl-line', { hasText: 'line 1' }).first()).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await v.locator('.bl-line', { hasText: 'nine' }).click()
  await expect(card()).toContainText('docs: move guide')
  await page.mouse.move(0, 0)
  await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur())
  await page.screenshot({ path: 'e2e-artifacts/blame.png' })
  await card().getByRole('button', { name: 'Blame at parent' }).click()
  await expect(head()).toContainText(`Revision: ${sha7['docs: edit guide']} · guide.txt`)
  await expect(chunks()).toHaveText(['docs: add guide', 'docs: edit guide', 'docs: add guide'])
  await v.locator('.bl-line').first().click()
  await expect(card()).toContainText('docs: add guide')
  await expect(card().getByRole('button', { name: 'Blame at parent' })).toBeDisabled()
  await v.getByRole('button', { name: 'Back to HEAD' }).click()
  await expect(head()).toContainText('Revision: HEAD')
  await entry('docs: move guide').focus()
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowDown')
  await expect(entry('docs: add guide')).toHaveAttribute('aria-selected', 'true')
  await expect(head()).toContainText(`Revision: ${sha7['docs: add guide']}`)
  await page.keyboard.press('Home')
  await expect(entry('docs: move guide')).toHaveAttribute('aria-selected', 'true')
  await expect(head()).toContainText(`Revision: ${sha7['docs: move guide']}`)
  await v.getByRole('group', { name: 'File view' }).getByRole('button', { name: 'Diff' }).click()
  await expect(v.locator('.center .line.add .t')).toHaveText(['nine'])
  await v.getByRole('button', { name: 'History', exact: true }).click()
})

